CREATE TABLE IF NOT EXISTS public.company_profile (
    id bigint primary key generated by default as identity,
    legal_name text not null default 'NEOMARC REALTY',
    trading_name text,
    rc_number text,
    tin text,
    vat_number text,
    phone text,
    email text,
    website text,
    address text,
    currency text not null default 'NGN',
    fiscal_year_start_month int not null default 1,
    vat_rate numeric not null default 0,
    wht_rate numeric not null default 0,
    timezone text not null default 'Africa/Lagos',
    site_name text DEFAULT 'NEOMARC REALTY',
    site_abbreviation text DEFAULT 'N',
    site_description text DEFAULT 'NEOMARC Digital Operating System',
    logo_url text,
    favicon_url text,
    updated_at timestamp with time zone default now(),
    updated_by uuid references auth.users(id)
);

