CREATE POLICY "Enable read access for all users" ON public.company_profile FOR SELECT USING (true);
CREATE POLICY "Enable update for admins" ON public.company_profile FOR UPDATE USING (
    EXISTS (SELECT 1 FROM public.user_roles WHERE user_id = auth.uid() AND role IN ('super_admin', 'management'))
);
CREATE POLICY "Enable insert for admins" ON public.company_profile FOR INSERT WITH CHECK (
    EXISTS (SELECT 1 FROM public.user_roles WHERE user_id = auth.uid() AND role IN ('super_admin', 'management'))
);

